import uuid
from datetime import datetime
from typing import Any, Dict, List, Literal, Optional
from pydantic import BaseModel, Field, ConfigDict


class PlanStep(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    step_number: int = Field(..., description="1-indexed step number")
    description: str = Field(..., description="Actionable description of the step")
    tool_required: Optional[str] = Field(None, description="Name of required tool, e.g. search_knowledge_base, query_incidents")
    requires_rag: bool = Field(False, description="Whether this step retrieves internal knowledge via RAG")
    requires_human_approval: bool = Field(False, description="Whether this step involves sensitive actions requiring human approval")
    status: Literal["PENDING", "RUNNING", "COMPLETED", "FAILED", "SKIPPED"] = Field("PENDING", description="Step execution status")
    output: Optional[str] = Field(None, description="Output or summary generated by the step")


class Plan(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    task_summary: str = Field(..., description="High-level understanding of the user request")
    steps: List[PlanStep] = Field(default_factory=list, description="Ordered execution steps")
    estimated_impact: Literal["LOW", "MEDIUM", "HIGH"] = Field("LOW", description="Risk/impact estimate")


class EvidenceItem(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    evidence_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    source_type: Literal["RAG_CHUNK", "TOOL_OUTPUT", "SYSTEM_METRIC", "LOG", "AGENT_OBSERVATION"] = Field(
        ..., description="Type of evidence"
    )
    source_identifier: str = Field(..., description="Identifier or source name (e.g. runbook name, tool name)")
    source_id: Optional[str] = Field(None, description="Optional ID of the source artifact or tool execution")
    source_description: Optional[str] = Field(None, description="Human-readable description of source")
    originating_agent: Optional[str] = Field(None, description="Specialist agent that collected this evidence")
    content: str = Field(..., description="Verbatim or summarized observation")
    evidence_class: Literal["FACT", "INFERENCE", "DOCUMENTATION", "OBSERVATION"] = Field(
        "FACT", description="Epistemic evidence classification"
    )
    confidence: float = Field(1.0, ge=0.0, le=1.0, description="Confidence score")
    timestamp: datetime = Field(default_factory=datetime.utcnow)


class SpecialistTask(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    task_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    target_agent: Literal["DiagnosticAgent", "KnowledgeAgent", "IncidentAgent"] = Field(
        ..., description="Target specialist agent"
    )
    task_description: str = Field(..., description="Clear instructions for the specialist")
    required_tools: List[str] = Field(default_factory=list, description="Tools expected to be used")
    status: Literal["PENDING", "RUNNING", "COMPLETED", "FAILED", "SKIPPED"] = "PENDING"
    completed_at: Optional[datetime] = None


class DelegationPlan(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    plan_summary: str = Field(..., description="Supervisor's decomposition rationale")
    tasks: List[SpecialistTask] = Field(default_factory=list)
    estimated_impact: Literal["LOW", "MEDIUM", "HIGH"] = "LOW"


class SpecialistResult(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    agent_name: str
    task_id: str
    task_description: str
    status: Literal["SUCCESS", "FAILED", "PARTIAL", "WAITING_APPROVAL"] = "SUCCESS"
    evidence_collected: List[EvidenceItem] = Field(default_factory=list)
    tools_used: List[str] = Field(default_factory=list)
    confidence: float = 1.0
    summary: str
    error: Optional[str] = None
    started_at: datetime = Field(default_factory=datetime.utcnow)
    completed_at: datetime = Field(default_factory=datetime.utcnow)


class ToolCallData(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    tool_call_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    tool_name: str
    tool_args: Dict[str, Any] = Field(default_factory=dict)
    timestamp: datetime = Field(default_factory=datetime.utcnow)


class ToolResultData(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    tool_call_id: str
    tool_name: str
    status: Literal["SUCCESS", "FAILED", "PENDING_APPROVAL", "REJECTED"] = "SUCCESS"
    output: Any = None
    error: Optional[str] = None
    latency_ms: Optional[float] = None
    requires_approval: bool = False


class ApprovalRequest(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    approval_id: uuid.UUID = Field(default_factory=uuid.uuid4)
    tool_name: str
    tool_args: Dict[str, Any]
    reason: str
    created_at: datetime = Field(default_factory=datetime.utcnow)


class ApprovalResult(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    approval_id: uuid.UUID
    approved: bool
    decided_by: str
    decided_at: datetime = Field(default_factory=datetime.utcnow)
    rejection_reason: Optional[str] = None


class AgentRunRequest(BaseModel):
    message: str = Field(..., min_length=2, description="User instruction or operational incident inquiry")
    conversation_id: Optional[str] = Field(None, description="Optional conversation tracking ID")


class AgentEventResponse(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    id: uuid.UUID
    run_id: uuid.UUID
    node_name: str
    event_type: str
    payload: Dict[str, Any] = Field(default_factory=dict)
    duration_ms: Optional[float] = None
    created_at: datetime


class ToolExecutionResponse(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    id: uuid.UUID
    run_id: uuid.UUID
    tool_name: str
    tool_input: Dict[str, Any]
    tool_output: Optional[Dict[str, Any]] = None
    status: str
    error: Optional[str] = None
    latency_ms: Optional[float] = None
    created_at: datetime


class AgentRunResponse(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    id: uuid.UUID
    conversation_id: str
    user_request: str
    status: str
    plan: Optional[Dict[str, Any]] = None
    final_answer: Optional[str] = None
    error: Optional[str] = None
    total_latency_ms: Optional[float] = None
    total_tokens: Optional[int] = 0
    tools_used: List[str] = Field(default_factory=list)
    number_of_tool_calls: int = 0
    agents_used: List[str] = Field(default_factory=list)
    delegation_count: int = 0
    evidence_count: int = 0
    approval_required: bool = False
    created_at: datetime
    updated_at: datetime
    events: Optional[List[AgentEventResponse]] = None
    tool_executions: Optional[List[ToolExecutionResponse]] = None
